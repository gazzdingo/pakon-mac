#!/usr/bin/env python3
"""Generate core/tables/vendor_manifest.def and core/tables/vendor_items.def (hashes and the item enum only).

usage: python3 -I tools/gen_vendor_manifest.py <Pakon dir> [--alt-root DIR]... [--readme vendor/README.md] [--out core/tables]

<Pakon dir> is the FULL install (".../fx35install/program files/Pakon"): the in-repo vendor/ tree lacks F235Driver,
F-335 and Config/Firmware. Each --alt-root is a flat folder (fx35install/, the CD root) whose same-named files with the
SAME hash become one more accepted path of the item. Only files vendor/README.md lists are cross-checked against it
(exit 1 on any difference); the others are taken from the install.

Required items (C21): the four F-135 firmware images. Everything else is optional; Config/Firmware/*.HEX is hash-only.
"""
import argparse, hashlib, os, re, sys

FX = "F-135/F135Driver"
FX35 = "FX35Driver"
F335 = "F-335/F335Driver"
F235 = "F235Driver"
FW = "F-X35 COM SERVER/Config/Firmware"

# (enum name, canonical relative path, extra directories whose same-named, same-hash file is an accepted path, required)
ITEMS = [
    ("PKV_PKNINIT_HEX",      FX + "/PknInit.hex", [FX35, F335], 1),
    ("PKV_PAKON5_HEX",       FX + "/Pakon5.hex",  [FX35, F335], 1),
    ("PKV_PAKON7_HEX_2004",  FX + "/Pakon7.hex",  [F335], 1),
    ("PKV_PAKON7_HEX_2006",  FX35 + "/Pakon7.hex", [], 0),
    ("PKV_PAKON8_HEX",       FX + "/Pakon8.hex",  [FX35, F335], 1),
    ("PKV_F235_PAKON_HEX",   F235 + "/Pakon.hex", [], 0),
    ("PKV_F235_PAKON1_HEX",  F235 + "/Pakon1.hex", [], 0),
    ("PKV_F235_PAKON2_HEX",  F235 + "/pakon2.hex", [], 0),
    ("PKV_F235_PAKON5_HEX",  F235 + "/Pakon5.hex", [], 0),
    ("PKV_F235_PKNINIT_HEX", F235 + "/PknInit.hex", [], 0),
]
for f in ("F235Ldr.sys", "F235Lib.sys", "F235usb2.inf", "F235usb2.sys", "F235Disk.tag", "LDRCFG.txt"):
    ITEMS.append(("PKV_F235_" + re.sub(r"\W", "_", f).upper(), F235 + "/" + f, [], 0))
for f in ("F135usb2.sys", "F235Disk.tag", "F235Ldr.sys", "F235Lib.sys", "F235usb2.inf", "F235usb2.sys", "FX35usb2.sys"):
    ITEMS.append(("PKV_F335_" + re.sub(r"\W", "_", f).upper(), F335 + "/" + f, [], 0))

def sha(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        h.update(f.read())
    return h.hexdigest()

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("pakon_dir")
    ap.add_argument("--alt-root", action="append", default=[])
    ap.add_argument("--readme", default="vendor/README.md")
    ap.add_argument("--out", default="core/tables")
    a = ap.parse_args()

    readme = {}
    with open(a.readme, encoding="utf-8") as f:
        for ln in f:
            m = re.match(r"^([0-9a-f]{64})  (.+?)\s*$", ln)
            if m:
                readme[m.group(2)] = m.group(1)

    items = list(ITEMS)
    fwdir = os.path.join(a.pakon_dir, FW)
    for n in sorted(os.listdir(fwdir), key=str.lower):
        if os.path.isfile(os.path.join(fwdir, n)):
            stem, ext = os.path.splitext(n)
            items.append(("PKV_FW_%s_%s" % (re.sub(r"\W", "_", stem).upper(), ext[1:].upper()), FW + "/" + n, [], 0))
    names = [i[0] for i in items]
    if len(set(names)) != len(names):
        sys.exit("duplicate item name")

    rows, bad, checked = [], 0, 0
    for name, canon, extra, required in items:
        full = os.path.join(a.pakon_dir, canon)
        if not os.path.isfile(full):
            sys.exit("missing in install: " + canon)
        digest, size = sha(full), os.path.getsize(full)
        paths = [canon]
        base = os.path.basename(canon)
        for d in extra:
            p = d + "/" + base
            fp = os.path.join(a.pakon_dir, p)
            if os.path.isfile(fp):
                if sha(fp) != digest:
                    sys.exit("accepted-path copy differs: " + p)
                paths.append(p)
        for root in a.alt_root:
            fp = os.path.join(root, base)
            if os.path.isfile(fp) and sha(fp) == digest and base not in paths:
                paths.append(base)
        if len(paths) > 4:
            sys.exit("more than 4 accepted paths: " + canon)
        for p in paths:
            if p in readme:
                checked += 1
                if readme[p] != digest:
                    print("README MISMATCH %s: README %s install %s" % (p, readme[p], digest), file=sys.stderr)
                    bad += 1
        hash_only = 1 if canon.startswith(FW + "/") else 0
        optional = 0 if required else 1
        rows.append((name, paths, size, digest, hash_only, optional))
    if bad:
        sys.exit(1)

    hdr = ("/* Generated by tools/gen_vendor_manifest.py from the full install (Pakon 3.0.4.27). Do not edit.\n"
           " * Hashes and sizes only; no Kodak bytes. README cross-checked paths: %d, all equal. */\n" % checked)
    with open(os.path.join(a.out, "vendor_items.def"), "w") as f:
        f.write(hdr + "/* PKV_ITEM(name): the pk_vendor_item enum, in manifest order */\n")
        for r in rows:
            f.write("PKV_ITEM(%s)\n" % r[0])
    with open(os.path.join(a.out, "vendor_manifest.def"), "w") as f:
        f.write(hdr)
        f.write("/* PK_VENDOR(ITEM, path1, path2, path3, path4, size, sha256, hash_only, optional)\n"
                " * paths: accepted relative locations under a Pakon tree (first = where the store keeps it); NULL = unused.\n"
                " * hash_only: Config/Firmware images, verified but never handed out. optional: absence is reported, not an error. */\n")
        for name, paths, size, digest, ho, opt in rows:
            ps = ["\"%s\"" % p for p in paths] + ["NULL"] * (4 - len(paths))
            f.write("PK_VENDOR(%s, %s, %d, \"%s\", %d, %d)\n" % (name, ", ".join(ps), size, digest, ho, opt))
    print("%d items (%d required), %d README cross-checks" % (len(rows), sum(1 for r in rows if not r[5]), checked))

if __name__ == "__main__":
    main()
